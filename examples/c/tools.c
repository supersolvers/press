static press_label_t news;

static void say(const char *text) {
    CHECK(press_label_set_text(news, PRESS_S(text)));
    printf("%s\n", text);
}

static void on_tool(press_button_t self, void *userdata) {
    (void)self;
    say(userdata);
}

static void on_copies(press_stepper_t self, int32_t value, void *userdata) {
    char text[40];
    (void)self;
    (void)userdata;
    snprintf(text, sizeof text, "%d %s", value, value == 1 ? "copy" : "copies");
    say(text);
}

static press_button_t tool(press_toolbar_t bar, const char *label, const uint8_t *png, size_t len, const char *help, const char *does) {
    press_button_t b;
    CHECK(press_button_new(PRESS_S(label), &b));
    CHECK(press_button_set_flat(b, true));
    CHECK(press_button_set_image(b, png, len));
    CHECK(press_widget_set_tooltip(b, PRESS_S(help)));
    CHECK(press_button_on_clicked(b, on_tool, (void *)does, NULL));
    CHECK(press_stack_add(bar, b));
    return b;
}

int main(int argc, char **argv) {
    const char *snapshot = (argc == 3 && strcmp(argv[1], "--snapshot") == 0) ? argv[2] : NULL;
    press_window_t window;
    press_stack_t column, body, row;
    press_toolbar_t bar;
    press_group_box_t paper;
    press_status_bar_t foot;
    press_label_t label, size_label;
    press_stepper_t copies;
    press_combo_box_t size;
    press_checkbox_t both;
    press_list_box_t inks;
    press_button_t save;

    CHECK(press_app_init());
    CHECK(press_window_new(PRESS_S("Tools"), 330, 250, &window));
    CHECK(press_stack_new(PRESS_ORIENTATION_VERTICAL, &column));
    CHECK(press_stack_set_spacing(column, 0));
    CHECK(press_stack_set_align(column, PRESS_ALIGN_FILL));

    /* the bar of tools */
    CHECK(press_toolbar_new(&bar));
    tool(bar, "New", NEW, sizeof NEW, "Begin a new sheet", "A new sheet.");
    tool(bar, "Open", OPEN, sizeof OPEN, "Open a sheet that was saved", "Opened.");
    save = tool(bar, "", SAVE, sizeof SAVE, "Save this sheet", "Saved.");
    CHECK(press_stack_add(column, bar));

    CHECK(press_stack_new(PRESS_ORIENTATION_HORIZONTAL, &body));
    CHECK(press_stack_set_padding(body, 12));
    CHECK(press_stack_set_spacing(body, 12));

    /* things that belong together, in a box */
    CHECK(press_group_box_new(PRESS_S("Paper"), PRESS_ORIENTATION_VERTICAL, &paper));
    CHECK(press_stack_new(PRESS_ORIENTATION_HORIZONTAL, &row));
    CHECK(press_stack_set_align(row, PRESS_ALIGN_CENTER));
    CHECK(press_label_new(PRESS_S("Copies:"), &label));
    CHECK(press_stepper_new(&copies));
    CHECK(press_stepper_set_min(copies, 1));
    CHECK(press_stepper_set_max(copies, 99));
    CHECK(press_stepper_set_value(copies, 2));
    CHECK(press_stepper_on_changed(copies, on_copies, NULL, NULL));
    CHECK(press_stack_add(row, label));
    CHECK(press_stack_add(row, copies));
    CHECK(press_stack_add(paper, row));

    CHECK(press_stack_new(PRESS_ORIENTATION_HORIZONTAL, &row));
    CHECK(press_stack_set_align(row, PRESS_ALIGN_CENTER));
    CHECK(press_label_new(PRESS_S("Size:"), &size_label));
    CHECK(press_combo_box_new(PRESS_S("A4"), &size));
    CHECK(press_text_field_set_min_width(size, 96));
    CHECK(press_combo_box_add(size, PRESS_S("A3")));
    CHECK(press_combo_box_add(size, PRESS_S("A4")));
    CHECK(press_combo_box_add(size, PRESS_S("Letter")));
    CHECK(press_stack_add(row, size_label));
    CHECK(press_stack_add(row, size));
    CHECK(press_stack_add(paper, row));

    CHECK(press_checkbox_new(PRESS_S("Both sides"), &both));
    CHECK(press_checkbox_set_checked(both, true));
    CHECK(press_stack_add(paper, both));
    CHECK(press_stack_add(body, paper));

    /* a list with pictures in colour */
    CHECK(press_list_box_new(&inks));
    CHECK(press_list_box_set_rows(inks, 5));
    CHECK(press_list_box_set_min_width(inks, 110));
    CHECK(press_list_box_add(inks, PRESS_S("Leaf")));
    CHECK(press_list_box_add(inks, PRESS_S("Water")));
    CHECK(press_list_box_add(inks, PRESS_S("Sun")));
    CHECK(press_list_box_set_image(inks, 0, LEAF, sizeof LEAF));
    CHECK(press_list_box_set_image(inks, 1, DROP, sizeof DROP));
    CHECK(press_list_box_set_image(inks, 2, SUN, sizeof SUN));
    CHECK(press_list_box_set_selected(inks, 1));
    CHECK(press_stack_add(body, inks));
    CHECK(press_stack_add(column, body));

    /* the bar of news */
    CHECK(press_status_bar_new(&foot));
    CHECK(press_label_new(PRESS_S("Ready."), &news));
    CHECK(press_stack_add(foot, news));
    /* each thing it says in a cell of its own, the first taking what room there is */
    CHECK(press_status_bar_set_panels(foot, true));
    CHECK(press_widget_set_stretch(news, 1));
    CHECK(press_label_new(PRESS_S("A4"), &label));
    CHECK(press_stack_add(foot, label));
    CHECK(press_label_new(PRESS_S("2 copies"), &label));
    CHECK(press_stack_add(foot, label));
    CHECK(press_stack_add(column, foot));

    CHECK(press_window_set_content(window, column));
    CHECK(press_window_fit(window));

    if (snapshot) {
        /* the pointer rests on the last tool: it shows its edge, and its word of help */
        CHECK(press_window_hover_at(window, 100, 14, 900));
        (void)save;
        CHECK(press_window_snapshot(window, PRESS_S(snapshot), 2));
    } else {
        CHECK(press_window_show(window));
        CHECK(press_app_run());
    }
    CHECK(press_app_shutdown());
    return 0;
}
