// What a whole program has round its dialogs, written with Press: a bar of
// tools with pictures and a word of help for each, a box with a title, a
// number to step, a text field with choices, and a bar of news.
//
//     swift run --package-path examples/swift ToolsUI
import Press

@main
struct ToolsUI: App {
    var body: some Scene {
        WindowGroup("Tools") { Sheet() }
    }
}

struct Sheet: View {
    @State private var copies = 2
    @State private var size = "A4"
    @State private var both = true
    @State private var news = "Ready."

    var body: some View {
        VStack(alignment: .fill, spacing: 0) {
            Toolbar {
                Button("New", png: Pictures.new) { news = "A new sheet." }
                    .help("Begin a new sheet")
                Button("Open", png: Pictures.open) { news = "Opened." }
                    .help("Open a sheet that was saved")
                Button("", png: Pictures.save) { news = "Saved." }
                    .help("Save this sheet")
            }
            GroupBox("Paper") {
                Stepper("Copies:", value: $copies, in: 1...99)
                HStack {
                    Text("Size:")
                    ComboBox("Size", text: $size, choices: ["A3", "A4", "Letter"])
                        .frame(width: 96)
                }
                Toggle("Both sides", isOn: $both)
            }
            .padding(12)
            StatusBar(panels: true) {
                Text(news)
                Text("\(copies) of \(size)\(both ? ", both sides" : "")")
            }
        }
    }
}

